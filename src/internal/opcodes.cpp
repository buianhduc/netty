const std::unordered_map<uint8_t, OpCode> InstructionTable = []() {
    std::unordered_map<uint8_t, OpCode> table;
    table.reserve(OP_CODES.size());
    for (const auto& opcode : OP_CODES) {
        table.emplace(opcode.code, opcode);
    }
    return table;
}();
